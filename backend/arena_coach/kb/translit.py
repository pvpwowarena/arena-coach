"""Латиница → кириллица для ГОЛОСА (Phase 4.14).

Зачем. Русский системный синтезатор («say -v Milena», Windows SAPI RU) читает
латиницу как попало: ник `Cekraj` превращается в набор букв, а `Cloak of Shadows`
— в кашу. При этом латиница в голосовой фразе появляется штатно, двумя путями:

* ники врагов — с Phase 4.14 их приходится называть, когда у врагов дубли классов
  («две роги» неразрешимо без имени);
* `kb.slang` для 46 слагов из 63 отдаёт `en_name` (`register: colloquial` или нет
  записи в лексиконе) — то есть английское имя способности внутри русской фразы.

Слой применяется ТОЛЬКО к голосу (в Discord DM человек читает нормальный текст,
и там латиница уместна). Это тот же принцип, что у `kb.pronunciation`: правим не
смысл, а звучание.

Транслитерация фонетическая и заведомо приблизительная — цель не «правильно по
ГОСТу», а «синтезатор произнёс узнаваемо». Порядок важен: сперва биграммы/триграммы
(`sh`, `ch`, `tion`), потом одиночные буквы.
"""

from __future__ import annotations

import re

#: Многобуквенные сочетания — применяются ПЕРВЫМИ и по длине (длинные раньше).
_DIGRAPHS: dict[str, str] = {
    "sch": "ш",
    "tch": "ч",
    "sh": "ш",
    "ch": "ч",
    "zh": "ж",
    "kh": "х",
    "ph": "ф",
    "th": "т",
    "ck": "к",
    "ts": "ц",
    "ya": "я",
    "yu": "ю",
    "yo": "ё",
    "ye": "е",
    "ee": "и",
    "oo": "у",
    "ou": "у",
    "ae": "э",
    "ei": "ей",
    "ay": "эй",
    "ey": "ей",
    "oy": "ой",
    "qu": "кв",
}

#: Одиночные буквы. `y` → «й» (после гласной обычно так и звучит), `x` → «кс».
_LETTERS: dict[str, str] = {
    "a": "а",
    "b": "б",
    "c": "к",
    "d": "д",
    "e": "е",
    "f": "ф",
    "g": "г",
    "h": "х",
    "i": "и",
    "j": "дж",
    "k": "к",
    "l": "л",
    "m": "м",
    "n": "н",
    "o": "о",
    "p": "п",
    "q": "к",
    "r": "р",
    "s": "с",
    "t": "т",
    "u": "у",
    "v": "в",
    "w": "в",
    "x": "кс",
    "y": "й",
    "z": "з",
}

_DIGRAPH_RE = re.compile(
    "|".join(sorted(map(re.escape, _DIGRAPHS), key=len, reverse=True)),
    flags=re.IGNORECASE,
)

#: Слово целиком из латиницы (с апострофами и дефисами внутри — бывают в никах).
_LATIN_WORD_RE = re.compile(r"[A-Za-z][A-Za-z'\-]*")


def translit_word(word: str) -> str:
    """`Cekraj` → `Кекрадж`. Не-латинские символы остаются как есть."""
    if not word:
        return word
    lowered = word.lower()
    out = _DIGRAPH_RE.sub(lambda m: _DIGRAPHS[m.group(0).lower()], lowered)
    out = "".join(_LETTERS.get(ch, ch) for ch in out)
    # `y` в начале слова звучит как «й» только перед согласной; перед гласной это «ь»-йот,
    # но для синтезатора достаточно оставить «й» — лишнего звука он не добавит.
    if not out:
        return word
    return out[:1].upper() + out[1:] if word[:1].isupper() else out


def latin_to_cyrillic(text: str) -> str:
    """Транслитерировать все латинские слова в строке. Кириллицу не трогает."""
    if not text:
        return text
    return _LATIN_WORD_RE.sub(lambda m: translit_word(m.group(0)), text)
