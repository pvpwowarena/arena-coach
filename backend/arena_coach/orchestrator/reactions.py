def ability_reaction(spell_key: str) -> Reaction | None:
    """Реакция на ключевой КД врага; None — если спелл не в таблице."""
    return ABILITY_REACTIONS.get(spell_key)


def trinket_reaction() -> Reaction:
    """Реакция на тринкет врага."""
    return TRINKET_REACTION
