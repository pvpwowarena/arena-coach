"""Реакции на события боя (Phase 4.10/4.11) — что ДЕЛАТЬ, а не что случилось.

История правок — по живым тестам, каждая строка ниже оплачена боем:

* 30.07 (4.10): «как будто анонсера зациклило и ничего полезного» → голос стал
  говорить реакцию, а не факт («Блок — стоп бурст, десять секунд по второму»).
* 30.07 (4.11): «нет подсказок по ходу боя», «старт + 1-2 реплики за матч» →
  выяснилось, что мост трекает 27 спеллов, а реакции были только на 13 «дефов и
  бурстов». Вся CC-механика (сап, чип, кидни, овца, нова, кс, страх, скрим, коил,
  циклон, подж, фридом, шауты) доезжала до бэкенда и отбрасывалась как `skipped`.
  Теперь покрыт весь трекаемый набор — тест `test_every_tracked_spell_answered`
  ловит расхождение с мостом.

Формы реплики:
  • `voice` — для TTS: ≤8 слов, императив, без ников. Длина тут не косметика:
    поллер моста синтезирует речь ПОСЛЕДОВАТЕЛЬНО и блокирующе, поэтому каждое
    лишнее слово — это задержка следующей подсказки;
  • `dm` — одна строка в текст. В бою игрок текст не читает («огромный текст в бою
    читать не очень удобно»), поэтому длинные планы из KB в in-fight DM больше не
    подклеиваются — они остались в `/matchup` и постматче.

Плюс два поля для анти-спама (см. `pipeline.HintThrottle`):
  • `priority` — `high` пробивает общий интервал между репликами (тринкет, стан
    под добивание, овца на хилере — решение принимается сейчас или никогда);
  • `repeat_s` — окно повтора того же ключа: CC сыплется часто (нова 25с КД,
    кидни каждые полминуты), тяжёлые КД — раз в бой.

**Тир.** Advice-тир (как 811 офлайн-разборов в `tools/advice_seed.json`), не KB:
правила KB (sourced + flagged + не аппрувить самому) сюда не распространяются.
Цифры и механика взяты из `kb/glossary/abilities.json` (sourced-слой) и указаны
комментарием у записи. Где записи в глоссарии нет (`GLOSSARY_GAPS`) — реплика без
секунд, механику 2.4.3 не экстраполируем.
"""

